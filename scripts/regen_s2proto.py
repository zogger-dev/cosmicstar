"""Regenerates the installed s2clientprotocol bindings in the modern protoc style so the
fast C++ (upb) protobuf implementation can load them, and patches s2protocol's version
loader for Python 3.12+ (it imports the removed imp module; see
patch_s2protocol_versions).

The s2clientprotocol wheel ships *_pb2.py files generated by an old protoc: they build
every descriptor with direct _descriptor.FieldDescriptor(...) calls, which the upb
implementation refuses ("Descriptors cannot be created directly"), so the extraction had
to force the pure-Python parser (44% of its frame time). But each old module embeds the
serialized FileDescriptorProto of its .proto file, which is all a modern module needs:
the new style just registers that blob with the default descriptor pool and lets the
builder create the classes. No .proto sources and no protoc are required.

Each regenerated module is written over the installed one (the original is kept next to
it as <name>.py.orig, restored with --restore). Run again after reinstalling or
upgrading the wheel.

    .venv-win/Scripts/python.exe scripts/regen_s2proto.py            # regenerate
    .venv-win/Scripts/python.exe scripts/regen_s2proto.py --check    # import under upb, parse a message
    .venv-win/Scripts/python.exe scripts/regen_s2proto.py --restore  # put the originals back
"""

import argparse
import glob
import importlib
import os
import shutil
import subprocess
import sys

TEMPLATE = '''# -*- coding: utf-8 -*-
# Regenerated by scripts/regen_s2proto.py from the serialized descriptor embedded in the
# original module (kept as {orig}); modern protoc style, loadable by the upb implementation.
# source: {source}
"""Generated protocol buffer code."""
from google.protobuf import descriptor as _descriptor
from google.protobuf import descriptor_pool as _descriptor_pool
from google.protobuf import symbol_database as _symbol_database
from google.protobuf.internal import builder as _builder
# @@protoc_insertion_point(imports)

_sym_db = _symbol_database.Default()

{imports}

DESCRIPTOR = _descriptor_pool.Default().AddSerializedFile({blob!r})

_globals = globals()
_builder.BuildMessageAndEnumDescriptors(DESCRIPTOR, _globals)
_builder.BuildTopDescriptorsAndMessages(DESCRIPTOR, {module!r}, _globals)
# @@protoc_insertion_point(module_scope)
'''


def package_dir():
    import s2clientprotocol

    return os.path.dirname(s2clientprotocol.__file__)


def regenerate():
    """Must run under the pure-Python implementation: only it can import the old
    modules."""
    os.environ["PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION"] = "python"
    d = package_dir()
    mods = sorted(
        os.path.basename(p)[:-3] for p in glob.glob(os.path.join(d, "*_pb2.py"))
    )
    files = {}
    for m in mods:
        orig = os.path.join(d, m + ".py.orig")
        src = os.path.join(d, m + ".py")
        if os.path.exists(orig):  # already regenerated once: start from the original
            shutil.copy(orig, src)
        mod = importlib.import_module("s2clientprotocol." + m)
        desc = mod.DESCRIPTOR
        deps = [
            dep.name for dep in desc.dependencies
        ]  # e.g. s2clientprotocol/common.proto
        imports = []
        for dep in deps:
            dep_mod = dep.replace(".proto", "_pb2").replace("/", ".")
            pkg, _, name = dep_mod.rpartition(".")
            alias = dep_mod.replace(".", "_dot_").replace("_pb2", "__pb2")
            imports.append(f"from {pkg} import {name} as {alias}")
        files[m] = TEMPLATE.format(
            orig=m + ".py.orig",
            source=desc.name,
            imports="\n".join(imports),
            blob=desc.serialized_pb,
            module="s2clientprotocol." + m,
        )
    for m, text in files.items():
        src, orig = os.path.join(d, m + ".py"), os.path.join(d, m + ".py.orig")
        if not os.path.exists(orig):
            shutil.copy(src, orig)
        open(src, "w", encoding="utf-8").write(text)
        print("regenerated", m)
    for p in glob.glob(os.path.join(d, "__pycache__", "*_pb2*.pyc")):
        os.remove(p)
    print(f"{len(files)} modules written to {d}")


VERSIONS_LOADER = """
def _import_protocol(base_path, protocol_module_name):
    \"\"\"Import a protocol module (patched by cosmicstar's scripts/regen_s2proto.py: the wheel's
    version uses imp, removed in Python 3.12; the original is __init__.py.orig).\"\"\"
    import importlib
    try:
        return sys.modules[protocol_module_name]
    except KeyError:
        pass
    return importlib.import_module(__name__ + "." + protocol_module_name)
"""


def versions_init():
    import s2protocol

    return os.path.join(os.path.dirname(s2protocol.__file__), "versions", "__init__.py")


def patch_s2protocol_versions():
    """s2protocol.versions (latest(), build()) loads protocol modules with imp, which
    Python 3.12 removed, so nothing that reads a replay header works there. Rewrites its
    _import_protocol with importlib; the original is kept as __init__.py.orig."""
    path = versions_init()
    orig = path + ".orig"
    if not os.path.exists(orig):
        shutil.copy(path, orig)
    text = open(orig, encoding="utf-8").read()
    if "import imp" not in text:
        print("s2protocol.versions needs no patch")
        return
    text = text.replace("import imp\n", "")
    start, end = text.index("def _import_protocol("), text.index("def list_all(")
    text = text[:start] + VERSIONS_LOADER.lstrip("\n") + "\n\n" + text[end:]
    open(path, "w", encoding="utf-8").write(text)
    for pyc in glob.glob(
        os.path.join(os.path.dirname(path), "__pycache__", "__init__*.pyc")
    ):
        os.remove(pyc)
    print("patched s2protocol.versions for Python 3.12+")


def restore():
    d = package_dir()
    n = 0
    for orig in glob.glob(os.path.join(d, "*_pb2.py.orig")):
        shutil.move(orig, orig[:-5])
        n += 1
    for p in glob.glob(os.path.join(d, "__pycache__", "*_pb2*.pyc")):
        os.remove(p)
    print(f"restored {n} modules")
    vi = versions_init()
    if os.path.exists(vi + ".orig"):
        shutil.move(vi + ".orig", vi)
        print("restored s2protocol.versions")


def check():
    """Imports the bindings under upb in a fresh interpreter and round-trips an
    observation."""
    code = r"""
import os, time
from google.protobuf.internal import api_implementation
from s2clientprotocol import sc2api_pb2 as sc_pb, raw_pb2 as raw_pb, common_pb2 as common
print("implementation:", api_implementation.Type())
o = sc_pb.ResponseObservation()
for i in range(500):
    u = o.observation.raw_data.units.add()
    u.tag = 2**32 + i; u.unit_type = 48 + i % 20; u.owner = 1 + i % 2; u.pos.x = 10.5 + i; u.pos.y = 20.25; u.pos.z = 8.0
    u.health = 45; u.health_max = 45; u.display_type = raw_pb.Visible; u.facing = 1.5
    for k in range(2):
        od = u.orders.add(); od.ability_id = 16; od.target_world_space_pos.x = 1.0; od.progress = 0.5
o.observation.game_loop = 1234
b = o.SerializeToString()
t = time.time()
for _ in range(200):
    p = sc_pb.ResponseObservation(); p.ParseFromString(b)
dt = (time.time() - t) / 200
assert p.observation.game_loop == 1234 and len(p.observation.raw_data.units) == 500 and p.observation.raw_data.units[7].pos.x == 17.5
print(f"ok: 500-unit observation parses in {dt*1000:.2f} ms ({len(b)} bytes)")
"""
    for impl in ("upb", "python"):
        env = dict(os.environ, PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION=impl)
        r = subprocess.run(
            [sys.executable, "-c", code], env=env, capture_output=True, text=True
        )
        print(
            f"[{impl}] "
            + (
                r.stdout.strip()
                if r.returncode == 0
                else "FAILED: " + r.stderr.strip()[-600:]
            )
        )


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--restore", action="store_true")
    a = ap.parse_args()
    if a.restore:
        restore()
    elif a.check:
        check()
    else:
        regenerate()
        patch_s2protocol_versions()
        check()
